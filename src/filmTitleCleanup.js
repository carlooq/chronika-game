const byId = new Map(CINEMA_TITLE_FIXES.map(x=>[x.id,x]));
export function eligibleCinemaTitleFix(record){
  const expected=byId.get(record?.id);
  if(!expected || record.title!==expected.oldTitle||record.year!==expected.year
     || !Array.isArray(record.categoryIds)||!record.categoryIds.includes('cinema'))return null;
  return {...expected};
}
export function previewCinemaTitleFixes(records){
  return records.map(eligibleCinemaTitleFix).filter(Boolean);
}
